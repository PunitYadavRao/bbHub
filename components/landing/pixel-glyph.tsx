export type GlyphName = keyof typeof ART;

/** One SVG path per colour; horizontal runs of pixels merge into single rectangles. */
function toPath(rows: readonly string[], pixel: string) {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== pixel) {
        x += 1;
        continue;
      }
      let run = 1;
      while (row[x + run] === pixel) run += 1;
      d += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  });
  return d;
}

const GLYPHS = Object.fromEntries(
  Object.entries(ART).map(([name, rows]) => [
    name,
    {
      width: Math.max(...rows.map((row) => row.length)),
      height: rows.length,
      base: toPath(rows, "#"),
      accent: toPath(rows, "+"),
    },
  ]),
) as Record<GlyphName, { width: number; height: number; base: string; accent: string }>;

export function PixelGlyph({ name, className }: { name: GlyphName; className?: string }) {
  const glyph = GLYPHS[name];
  return (
    <svg
      viewBox={`0 0 ${glyph.width} ${glyph.height}`}
      className={className}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <path d={glyph.base} fill="currentColor" />
      {glyph.accent ? <path d={glyph.accent} className="px-accent" /> : null}
    </svg>
  );
}
